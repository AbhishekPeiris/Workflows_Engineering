// --- MAIN REPORT GENERATION ---
async function generateReportFile(topic, tableData, metadata = {}) {
  const doc = new PDFDocument({
    margin: 40,
    size: "A4",
    info: {
      Title: `${topic} - WORKFLOWS ENGINEERING`,
      Author: "WORKFLOWS ENGINEERING",
      Subject: "Professional Attendance Report",
      Creator: "WSPM Report Management System",
      Keywords: "attendance, report, construction, management",
    },
  });

  const fileName = `Professional_Report_${Date.now()}.pdf`;
  const reportsDir = path.join(__dirname, "../reports");
  if (!fs.existsSync(reportsDir)) {
    fs.mkdirSync(reportsDir, { recursive: true });
  }
  const filePath = path.join(reportsDir, fileName);
  const stream = fs.createWriteStream(filePath);
  doc.pipe(stream);

  // HEADER
  buildHeader(doc);

  // META
  buildMeta(doc, {
    title: topic,
    month: metadata.month || "",
    generatedDate: metadata.generatedDate || new Date().toLocaleDateString(),
    generatedBy: metadata.generatedBy || "HR Department",
    docId:
      metadata.docId ||
      `RPT-${new Date().getFullYear()}-ATT-${String(
        new Date().getMonth() + 1
      ).padStart(3, "0")}`,
    status: metadata.status || "Official Document",
  });

  // EXECUTIVE SUMMARY
  sectionHeader(doc, "Executive Summary");
  // Calculate summary
  const totalEmployees = tableData.length;
  const totalPresent = tableData.reduce(
    (sum, row) => sum + parseInt(row.present || 0),
    0
  );
  const totalAbsent = tableData.reduce(
    (sum, row) => sum + parseInt(row.absent || 0),
    0
  );
  const totalOTHours = tableData.reduce(
    (sum, row) => sum + parseFloat(row.otHours || 0),
    0
  );
  const totalDays = tableData.reduce((max, row) => {
    const days = parseInt(row.present || 0) + parseInt(row.absent || 0);
    return days > max ? days : max;
  }, 0);
  const avgAttendance = totalDays
    ? ((totalPresent / (totalEmployees * totalDays)) * 100).toFixed(1)
    : "0.0";
  const avgOTPerEmployee =
    totalEmployees > 0 ? (totalOTHours / totalEmployees).toFixed(1) : "0.0";
  buildSummaryTable(doc, {
    totalEmployees,
    totalDays,
    totalPresent,
    totalAbsent,
    avgAttendance,
    totalOTHours: totalOTHours.toFixed(1),
    avgOTPerEmployee,
  });

  // DETAILED TABLE
  sectionHeader(doc, "Detailed Attendance & Overtime Report");
  buildDetailedTable(doc, tableData);

  // PERFORMANCE SUMMARY
  sectionHeader(doc, "Attendance Performance Summary");
  buildPerformanceSummary(doc, tableData);

  // OVERTIME DISTRIBUTION
  sectionHeader(doc, "Overtime Distribution");
  buildOTDistribution(doc, tableData);

  // SIGNATURE SECTION
  sectionHeader(doc, "Authorization & Approval");
  buildSignatureSection(doc);

  // FOOTER
  buildFooter(doc);

  doc.end();

  return new Promise((resolve, reject) => {
    stream.on("finish", () => resolve(filePath));
    stream.on("error", reject);
  });
}

module.exports = { generateReportFile };
