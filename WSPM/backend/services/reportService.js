const PDFDocument = require("pdfkit");
const fs = require("fs");
const path = require("path");

// Theme colors and fonts matching the HTML
const COLORS = {
  primary: "#002b5b",
  secondary: "#555",
  accent: "#f4f7fb",
  border: "#ccc",
  text: "#222",
  tableEven: "#fafafa",
  tableOdd: "#fff",
  blue: "#3498db",
  good: "#27ae60",
  warning: "#f39c12",
  danger: "#e74c3c",
  gray: "#444",
  lightGray: "#f4f7fb",
};
const FONT_FAMILY = "Helvetica";

// --- HEADER ---
function buildHeader(doc) {
  // Company name
  doc
    .font(FONT_FAMILY + "-Bold")
    .fontSize(26)
    .fillColor(COLORS.primary)
    .text("WORKFLOWS ENGINEERING", { align: "center" });
  // Tagline
  doc
    .font(FONT_FAMILY)
    .fontSize(15)
    .fillColor(COLORS.secondary)
    .text("Professional Construction Management Solutions", {
      align: "center",
    });
  doc
    .fontSize(12)
    .fillColor(COLORS.secondary)
    .text("BUILD YOUR DREAMS", { align: "center" });
  // Divider
  doc.moveDown(0.5);
  doc
    .lineWidth(3)
    .strokeColor(COLORS.primary)
    .moveTo(40, doc.y)
    .lineTo(doc.page.width - 40, doc.y)
    .stroke();
  doc.moveDown(1.5);
}

// --- META SECTION ---
function buildMeta(doc, meta) {
  doc.fontSize(13).fillColor(COLORS.gray).font(FONT_FAMILY);
  const metaLines = [
    { label: "Report Title:", value: meta.title },
    { label: "Month:", value: meta.month },
    { label: "Report Generated:", value: meta.generatedDate },
    { label: "Generated By:", value: meta.generatedBy },
    { label: "Document ID:", value: meta.docId },
    { label: "Status:", value: meta.status },
  ];
  metaLines.forEach((line) => {
    doc.text(`${line.label} ${line.value}`, { align: "right" });
  });
  doc.moveDown(1);
}

// --- SECTION HEADER ---
function sectionHeader(doc, text) {
  doc.moveDown(1.2);
  doc
    .font(FONT_FAMILY + "-Bold")
    .fontSize(16)
    .fillColor(COLORS.primary)
    .text(text.toUpperCase());
  doc
    .lineWidth(2)
    .strokeColor(COLORS.primary)
    .moveTo(40, doc.y)
    .lineTo(doc.page.width - 40, doc.y)
    .stroke();
  doc.moveDown(0.5);
}

// --- EXECUTIVE SUMMARY TABLE ---
function buildSummaryTable(doc, summary) {
  const rows = [
    ["Total Employees", summary.totalEmployees],
    ["Total Working Days", summary.totalDays],
    ["Total Present Days", summary.totalPresent],
    ["Total Absent Days", summary.totalAbsent],
    ["Average Attendance", summary.avgAttendance + "%"],
    ["Total OT Hours", summary.totalOTHours + " hours"],
    ["Average OT per Employee", summary.avgOTPerEmployee + " hours"],
  ];
  doc.fontSize(15).font(FONT_FAMILY);
  const startY = doc.y;
  rows.forEach(([label, value], idx) => {
    doc
      .rect(40, doc.y, (doc.page.width - 80) / 2, 22)
      .fillColor(idx % 2 === 0 ? COLORS.accent : COLORS.tableOdd)
      .fill();
    doc
      .rect(
        40 + (doc.page.width - 80) / 2,
        doc.y,
        (doc.page.width - 80) / 2,
        22
      )
      .fillColor(idx % 2 === 0 ? COLORS.accent : COLORS.tableOdd)
      .fill();
    doc
      .fillColor(COLORS.primary)
      .text(label, 48, doc.y + 5, { width: (doc.page.width - 80) / 2 - 16 });
    doc
      .fillColor(COLORS.text)
      .text(value, 48 + (doc.page.width - 80) / 2, doc.y + 5, {
        width: (doc.page.width - 80) / 2 - 16,
      });
    doc.y += 22;
  });
  doc.moveDown(1);
}

// --- DETAILED TABLE ---
function buildDetailedTable(doc, tableData) {
  // Table headers
  const headers = [
    "#",
    "Employee ID",
    "Employee Name",
    "Present",
    "Absent",
    "OT Hours",
    "Attendance %",
    "Performance",
  ];
  const colWidths = [28, 70, 110, 55, 55, 65, 70, 90];
  const startX = 40;
  let y = doc.y + 8;

  // Header row
  doc
    .rect(startX, y, doc.page.width - 80, 24)
    .fillColor(COLORS.accent)
    .fill();
  let x = startX;
  doc
    .font(FONT_FAMILY + "-Bold")
    .fontSize(14)
    .fillColor(COLORS.primary);
  headers.forEach((h, i) => {
    doc.text(h, x + 6, y + 6, { width: colWidths[i] - 12, align: "left" });
    x += colWidths[i];
  });
  y += 24;

  // Data rows
  tableData.forEach((row, idx) => {
    x = startX;
    doc
      .rect(x, y, doc.page.width - 80, 22)
      .fillColor(idx % 2 === 0 ? COLORS.tableEven : COLORS.tableOdd)
      .fill();
    doc.font(FONT_FAMILY).fontSize(13).fillColor(COLORS.text);

    // Attendance calculations
    const total = parseInt(row.present || 0) + parseInt(row.absent || 0) || 1;
    const percentage = ((parseInt(row.present || 0) / total) * 100).toFixed(1);
    const performance =
      percentage >= 95
        ? "Excellent"
        : percentage >= 90
        ? "Very Good"
        : percentage >= 80
        ? "Good"
        : percentage >= 70
        ? "Fair"
        : "Poor";
    const otHours = parseFloat(row.otHours || 0).toFixed(1);

    const rowData = [
      (idx + 1).toString(),
      row.workerId || "N/A",
      row.name || "N/A",
      (row.present || 0).toString(),
      (row.absent || 0).toString(),
      `${otHours}h`,
      `${percentage}%`,
      performance,
    ];

    rowData.forEach((cell, i) => {
      let color = COLORS.text;
      if (i === 5)
        color =
          otHours > 40
            ? COLORS.danger
            : otHours > 20
            ? COLORS.warning
            : COLORS.good;
      if (i === 6 || i === 7)
        color =
          percentage >= 90
            ? COLORS.good
            : percentage >= 80
            ? COLORS.warning
            : COLORS.danger;
      doc
        .fillColor(color)
        .text(cell, x + 6, y + 5, { width: colWidths[i] - 12, align: "left" });
      x += colWidths[i];
    });
    y += 22;
    // Page break if needed
    if (y > doc.page.height - 120) {
      doc.addPage();
      y = 60;
    }
  });
  doc.y = y + 8;
}

// --- PERFORMANCE SUMMARY TABLE ---
function buildPerformanceSummary(doc, tableData) {
  // Attendance performance
  const performanceStats = {
    excellent: 0,
    veryGood: 0,
    good: 0,
    fair: 0,
    poor: 0,
  };
  tableData.forEach((row) => {
    const total = parseInt(row.present || 0) + parseInt(row.absent || 0) || 1;
    const percentage = (parseInt(row.present || 0) / total) * 100;
    if (percentage >= 95) performanceStats.excellent++;
    else if (percentage >= 90) performanceStats.veryGood++;
    else if (percentage >= 80) performanceStats.good++;
    else if (percentage >= 70) performanceStats.fair++;
    else performanceStats.poor++;
  });
  const perfRows = [
    ["Excellent (95%+)", performanceStats.excellent],
    ["Very Good (90–94%)", performanceStats.veryGood],
    ["Good (80–89%)", performanceStats.good],
    ["Fair (70–79%)", performanceStats.fair],
    ["Poor (<70%)", performanceStats.poor],
  ];
  // Table
  doc.fontSize(13).font(FONT_FAMILY);
  let y = doc.y + 8;
  perfRows.forEach(([label, count], idx) => {
    doc
      .rect(40, y, (doc.page.width - 80) / 2, 20)
      .fillColor(idx % 2 === 0 ? COLORS.accent : COLORS.tableOdd)
      .fill();
    doc
      .rect(40 + (doc.page.width - 80) / 2, y, (doc.page.width - 80) / 2, 20)
      .fillColor(idx % 2 === 0 ? COLORS.accent : COLORS.tableOdd)
      .fill();
    doc
      .fillColor(COLORS.primary)
      .text(label, 48, y + 4, { width: (doc.page.width - 80) / 2 - 16 });
    doc
      .fillColor(COLORS.text)
      .text(count, 48 + (doc.page.width - 80) / 2, y + 4, {
        width: (doc.page.width - 80) / 2 - 16,
      });
    y += 20;
  });
  doc.y = y + 8;
}

// --- OVERTIME DISTRIBUTION TABLE ---
function buildOTDistribution(doc, tableData) {
  const otStats = { high: 0, medium: 0, low: 0, none: 0 };
  tableData.forEach((row) => {
    const ot = parseFloat(row.otHours || 0);
    if (ot > 40) otStats.high++;
    else if (ot > 20) otStats.medium++;
    else if (ot > 0) otStats.low++;
    else otStats.none++;
  });
  const otRows = [
    ["High OT (>40h)", otStats.high],
    ["Medium OT (20–40h)", otStats.medium],
    ["Low OT (1–20h)", otStats.low],
    ["No OT (0h)", otStats.none],
  ];
  let y = doc.y + 8;
  otRows.forEach(([label, count], idx) => {
    doc
      .rect(40, y, (doc.page.width - 80) / 2, 20)
      .fillColor(idx % 2 === 0 ? COLORS.accent : COLORS.tableOdd)
      .fill();
    doc
      .rect(40 + (doc.page.width - 80) / 2, y, (doc.page.width - 80) / 2, 20)
      .fillColor(idx % 2 === 0 ? COLORS.accent : COLORS.tableOdd)
      .fill();
    doc
      .fillColor(COLORS.primary)
      .text(label, 48, y + 4, { width: (doc.page.width - 80) / 2 - 16 });
    doc
      .fillColor(COLORS.text)
      .text(count, 48 + (doc.page.width - 80) / 2, y + 4, {
        width: (doc.page.width - 80) / 2 - 16,
      });
    y += 20;
  });
  doc.y = y + 8;
}

